"""Compiles ParticleInstanced.hlsl into ../ParticleShaderCode.h, run it again after editing the shader."""

import os
import subprocess
import sys
import tempfile

FXC = r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\fxc.exe"
HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "ParticleInstanced.hlsl")
OUTPUT = os.path.join(HERE, "..", "ParticleShaderCode.h")


def variant_name(lit, light_enabled, local_lights, shadow):
    if not (lit and light_enabled):
        local_lights = 0

    return "s_particle%s_le%d_ll%d_sh%d" % ("Lit" if lit else "Unlit", light_enabled, local_lights, shadow)


def compile_variant(lit, light_enabled, local_lights, shadow):
    with tempfile.TemporaryDirectory() as temp:
        target = os.path.join(temp, "out.o")
        defines = ["/DLIT=%d" % lit, "/DLIGHT_ENABLED=%d" % light_enabled, "/DLOCAL_LIGHTS=%d" % local_lights, "/DSHADOW=%d" % shadow]
        subprocess.run([FXC, "/nologo", "/T", "vs_3_0", "/E", "main", "/O3", *defines, "/Fo", target, SOURCE], check=True, stdout=subprocess.DEVNULL)

        with open(target, "rb") as f:
            return f.read()


def main():
    arrays = {}
    table = []

    for lit in range(2):
        for shadow in range(3):
            for local_lights in range(5):
                for light_enabled in range(2):
                    name = variant_name(lit, light_enabled, local_lights, shadow)

                    if name not in arrays:
                        arrays[name] = compile_variant(lit, light_enabled, local_lights if lit and light_enabled else 0, shadow)

                    table.append(name)

    lines = [
        "#ifndef PARTICLE_SHADER_CODE_H",
        "#define PARTICLE_SHADER_CODE_H",
        "",
        "#include <cstdint>",
        "",
        "// Generated by Shaders/GenerateParticleShaders.py from Shaders/ParticleInstanced.hlsl, do not edit by hand.",
        "namespace ParticleShaderCode {",
        "",
    ]

    for name, code in arrays.items():
        lines.append("static const uint8_t %s[] = {" % name)

        for i in range(0, len(code), 16):
            lines.append("    " + ", ".join("0x%02X" % b for b in code[i:i + 16]) + ",")

        lines.append("};")
        lines.append("")

    lines.append("struct Variant {")
    lines.append("    const char* m_name;")
    lines.append("    const uint8_t* m_code;")
    lines.append("    uint32_t m_size;")
    lines.append("};")
    lines.append("")
    lines.append("// Indexed by lit * 30 + lightEnabled + 2 * localLights + 10 * shadow.")
    lines.append("static const Variant s_variants[60] = {")

    for name in table:
        lines.append("    { \"HoT_%s\", %s, sizeof(%s) }," % (name[2:], name, name))

    lines.append("};")
    lines.append("")
    lines.append("}")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(OUTPUT, "w", newline="\n") as f:
        f.write("\n".join(lines))

    print("%d variants, %d distinct" % (len(table), len(arrays)))


if __name__ == "__main__":
    sys.exit(main())
