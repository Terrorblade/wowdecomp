#ifndef WOW_SOURCE_UI_LFGROLES_H
#define WOW_SOURCE_UI_LFGROLES_H

#include <cstdint>

enum ROLE_FLAGS : int32_t {
    ROLE_NONE = 0x0,
    ROLE_LEADER = 0x1,
    ROLE_TANK = 0x2,
    ROLE_HEALER = 0x4,
    ROLE_DAMAGER = 0x8,
    ROLE_COMBAT_ROLES = ROLE_TANK | ROLE_HEALER | ROLE_DAMAGER,
};

enum ROLE_FLAGS_8 : uint8_t {
    ROLE8_NONE = ROLE_NONE,
    ROLE8_LEADER = ROLE_LEADER,
    ROLE8_TANK = ROLE_TANK,
    ROLE8_HEALER = ROLE_HEALER,
    ROLE8_DAMAGER = ROLE_DAMAGER,
    ROLE8_COMBAT_ROLES = ROLE_COMBAT_ROLES,
};

#endif
